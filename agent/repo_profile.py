"""Repository Intelligence & Compliance — a permanent pre-ship pipeline stage.

Before any outward action (fork/push/PR), scan the repository itself and build a
persistent RepoProfile of its contribution requirements and policies; produce a
compliance report; and gate shipping — if any MANDATORY requirement cannot be
satisfied, shipping STOPS.

Detection is evidence-based (from the checkout + gh), each requirement carrying a
confidence and its source. Reuses ``agent.contribution_reqs`` for the
artifact-generation requirements (changelog / DCO / CLA / PR template) and adds
the policy layer (AI disclosure, issue linkage, duplicate policy, conventions,
workflows). Profiles are cached and only re-scanned when the repo HEAD changes.
"""

import datetime
import json
import os
import re

from agent import contribution_reqs as CR

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PROFILE_DIR = os.path.join(_ROOT, "repo_profiles")

# Bump whenever the detection schema changes. A cached profile written by an
# older scanner may be MISSING a requirement (e.g. AI disclosure) — using it
# would silently weaken the compliance gate — so a version mismatch forces a
# fresh scan even when the repo HEAD is unchanged.
SCANNER_VERSION = 4   # 4: markdown CHANGELOG.md detection (1b522dd)

# Dedicated AI-contribution policy files some repos keep OUTSIDE CONTRIBUTING
# (audit: go-git's CONTRIBUTING merely links AI_POLICY.md, whose disclosure
# mandate the scanner never saw — PR #2238 shipped non-compliant).
_AI_POLICY_PATHS = ("AI_POLICY.md", ".github/AI_POLICY.md", "AI_USAGE.md",
                    "AI_CONTRIBUTING.md", "docs/AI_POLICY.md")

# What the v2 pipeline can satisfy automatically.
_AUTO = {"changelog_changie", "dco", "issue_linkage", "pr_template",
         "ai_disclosure_title", "ai_disclosure_body"}


def _read(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _contributing(path):
    for cf in CR._CONTRIB_PATHS:
        p = os.path.join(path, cf)
        if os.path.isfile(p):
            return _read(p), cf
    return "", None


def _find_evidence(text, needles):
    low = text.lower()
    for n in needles:
        if n in low:
            return n
    return None


# ── policy detection ────────────────────────────────────────────────────────

def _ai_policy_text(path):
    """Text + source of a dedicated AI policy file, if the repo ships one."""
    for rel in _AI_POLICY_PATHS:
        p = os.path.join(path, rel)
        if os.path.isfile(p):
            return _read(p), rel
    return "", None


def _detect_ai_disclosure(contrib, contrib_src):
    lc = contrib.lower()
    mentions_ai = any(k in lc for k in (
        "ai usage", "generative ai", "llm agent", "ai tools", "ai-generated",
        "large language model", "ai assistance", "ai-assisted",
        "autogenerated with ai", "assisted-by", "ai contribution"))
    wants_disclosure = ("disclos" in lc or "self-disclosure" in lc
                        or "🤖" in contrib)
    required = mentions_ai and wants_disclosure
    m = re.search(r"(🤖+)", contrib)
    # Repos without a title marker (e.g. caddy's "Assistance Disclosure" PR
    # section) still get a satisfiable format: we author the PR body, so we
    # can always state the assistance there.
    fmt = (f"include {m.group(1)} in the PR title" if m
           else "state AI assistance in the PR body" if required else None)
    human_owned = ("human-owned account" in lc or "real, human" in lc
                   or "not accept submissions from bot" in lc
                   or "created by bots" in lc)
    return {
        "required": required,
        "format": fmt,
        "marker": m.group(1) if m else None,
        # Some policies (go-git) additionally want an Assisted-by: commit
        # trailer — recorded for the operator; not auto-satisfied.
        "commit_trailer": "Assisted-by" if "assisted-by" in lc else None,
        "human_owned_required": human_owned,
        "auto": bool(fmt),               # title marker or body statement
        "mandatory": required,
        "confidence": 0.85 if required else (0.3 if mentions_ai else 0.6),
        "evidence": f"{contrib_src} (AI Usage)" if required else None,
    }


def _detect_issue_linkage(contrib):
    ev = _find_evidence(contrib, [
        "reference the issue", "link the issue", "associated issue",
        "fixes #", "closes #", "resolves #", "link to the issue"])
    return {"required": bool(ev), "auto": True,  # we add "Fixes #N"
            "mandatory": False, "confidence": 0.6 if ev else 0.3,
            "evidence": ev}


def _detect_duplicate_policy(contrib):
    ev = _find_evidence(contrib, [
        "duplicate", "already working", "search existing", "existing pull",
        "someone is already", "check for existing"])
    return {"check_required": True, "auto": True,  # we always run the check
            "mandatory": True, "confidence": 0.7 if ev else 0.5,
            "evidence": ev or "policy inferred (always check)"}


def _detect_commit_conventions(path, contrib):
    for cfg in ("commitlint.config.js", ".commitlintrc", ".commitlintrc.json",
                ".commitlintrc.yml"):
        if os.path.isfile(os.path.join(path, cfg)):
            return {"convention": "conventional-commits (commitlint)",
                    "auto": False, "mandatory": True, "confidence": 0.8,
                    "evidence": cfg}
    ev = _find_evidence(contrib, ["conventional commit", "commit message format",
                                  "commit message convention"])
    return {"convention": ev, "auto": False, "mandatory": bool(ev),
            "confidence": 0.5 if ev else 0.2, "evidence": ev}


def _detect_workflows(path):
    wdir = os.path.join(path, ".github", "workflows")
    names, enforcers = [], []
    if os.path.isdir(wdir):
        for f in sorted(os.listdir(wdir)):
            if not f.endswith((".yml", ".yaml")):
                continue
            names.append(f)
            t = _read(os.path.join(wdir, f)).lower()
            if "changelog" in t and ("enforce" in f.lower() or "changelog" in f.lower()):
                enforcers.append(f"{f} (changelog)")
            if "cla" in t or "license/cla" in t:
                enforcers.append(f"{f} (cla)")
    return {"count": len(names), "enforcers": enforcers,
            "confidence": 0.5, "note": "required-status set needs branch-protection API"}


# ── scan / persist ──────────────────────────────────────────────────────────

def scan(path, repo, *, head_sha=None, now=None):
    """Build a RepoProfile from the checkout."""
    cr = CR.detect(path)
    contrib, contrib_src = _contributing(path)

    reqs = {}
    cl = cr.get("changelog")
    if cl:
        kind = cl["kind"]
        # A markdown CHANGELOG.md is satisfiable only for repos with an
        # explicit renderer profile; every other markdown repo is mandatory
        # but not auto -> compliance blocker, never a silent pass.
        auto = kind == "changie" or (kind == "markdown"
                                     and CR.markdown_supported(repo))
        evidence = {"changie": ".changie.yaml",
                    "markdown": cl.get("evidence") or "CHANGELOG.md"}.get(
                        kind, cl.get("dir", "CHANGELOG.md"))
        reqs["changelog"] = {
            "system": kind,
            "changes_dir": cl.get("changes_dir"),
            "unreleased_dir": cl.get("unreleased_dir"),
            "kinds": cl.get("kinds"),
            "auto": auto,
            "mandatory": True,
            "confidence": 1.0 if kind == "changie" else 0.6,
            "evidence": evidence,
        }
    else:
        reqs["changelog"] = {"system": None, "auto": False, "mandatory": False,
                             "confidence": 0.5, "evidence": None}

    reqs["cla"] = {"required": cr["cla"], "auto": False,
                   "manual": "human signs via CLA bot", "mandatory": cr["cla"],
                   "confidence": 0.9 if cr["cla"] else 0.5,
                   "evidence": contrib_src if cr["cla"] else None}
    reqs["dco"] = {"required": cr["dco"], "auto": True, "mandatory": cr["dco"],
                   "confidence": 0.9 if cr["dco"] else 0.5,
                   "evidence": contrib_src if cr["dco"] else None}
    reqs["pr_template"] = {"present": bool(cr["pr_template"]), "auto": True,
                           "mandatory": False,
                           "confidence": 1.0 if cr["pr_template"] else 0.7}
    ai_text, ai_src = _ai_policy_text(path)
    if ai_text:
        reqs["ai_disclosure"] = _detect_ai_disclosure(
            contrib + "\n" + ai_text, ai_src)
    else:
        reqs["ai_disclosure"] = _detect_ai_disclosure(contrib, contrib_src)
    reqs["issue_linkage"] = _detect_issue_linkage(contrib)
    reqs["duplicate_policy"] = _detect_duplicate_policy(contrib)
    reqs["commit_conventions"] = _detect_commit_conventions(path, contrib)
    reqs["workflows"] = _detect_workflows(path)

    stamp = (now or datetime.datetime.now().astimezone()).isoformat()
    return {"repo": repo, "scanner_version": SCANNER_VERSION,
            "scanned_at": stamp, "head_sha": head_sha, "requirements": reqs,
            "learned": {"maintainer_prefs": [], "failure_modes": [],
                        "events": []}}


def _profile_path(repo):
    return os.path.join(PROFILE_DIR, repo.replace("/", "__") + ".json")


def load(repo):
    p = _profile_path(repo)
    if os.path.isfile(p):
        try:
            return json.load(open(p))
        except (json.JSONDecodeError, OSError):
            return None
    return None


def save(profile):
    os.makedirs(PROFILE_DIR, exist_ok=True)
    dest = _profile_path(profile["repo"])
    # Write-then-rename so a concurrent reader/writer never sees a half-written
    # profile (os.replace is atomic on the same filesystem).
    tmp = dest + f".tmp.{os.getpid()}"
    try:
        with open(tmp, "w") as f:
            json.dump(profile, f, indent=2)
        os.replace(tmp, dest)
    except Exception:
        if os.path.exists(tmp):
            os.remove(tmp)          # don't orphan a partial temp file
        raise


def get_profile(path, repo, *, head_sha=None, force=False):
    """Load a cached profile, re-scanning only when the repo HEAD changed (repo
    metadata change) or when forced. Preserves the learned section across scans."""
    cached = None if force else load(repo)
    # Reuse only a same-schema, same-HEAD cache — never let an older-scanner
    # profile silently override the current policy set.
    if (cached and cached.get("scanner_version") == SCANNER_VERSION
            and cached.get("head_sha") and head_sha
            and cached["head_sha"] == head_sha):
        return cached
    fresh = scan(path, repo, head_sha=head_sha)
    if cached and cached.get("learned"):
        fresh["learned"] = cached["learned"]   # keep accumulated knowledge
    save(fresh)
    return fresh


# ── compliance report + gate ────────────────────────────────────────────────

def compliance_report(profile, *, is_duplicate=False, human_owned=True,
                      changelog_probe=None):
    """Return {rows:[...], blockers:[...], ok:bool}. Each row:
    {requirement, evidence, mandatory, auto_satisfied, manual_required,
     satisfied, confidence, note}.

    Defensive: a missing requirement key degrades to an empty dict rather than
    crashing the gate (a real scan always provides every key)."""
    from collections import defaultdict
    r = defaultdict(dict, profile.get("requirements", {}))
    rows = []

    def row(name, mandatory, satisfied, *, auto=False, manual=False,
            confidence=0.5, evidence=None, note=""):
        rows.append({"requirement": name, "mandatory": mandatory,
                     "auto_satisfied": auto and satisfied,
                     "manual_required": manual, "satisfied": satisfied,
                     "confidence": confidence, "evidence": evidence, "note": note})

    # Every sub-field is read via .get() with a safe default, so a partial or
    # hand-edited/truncated cached profile degrades gracefully rather than
    # crashing the outward gate. A malformed changelog/ai dict simply reads as
    # not-mandatory (skipped) rather than raising.
    dup, cl, ai = r["duplicate_policy"], r["changelog"], r["ai_disclosure"]
    cla, dco, il, cc = r["cla"], r["dco"], r["issue_linkage"], r["commit_conventions"]

    # duplicate — a hard STOP if the issue is already being addressed
    row("no duplicate work", True, not is_duplicate, auto=True, confidence=0.9,
        evidence=dup.get("evidence"),
        note="issue already has a linked/open PR" if is_duplicate else "")

    if cl.get("mandatory"):
        # `auto` (not system == changie) is the satisfiability test, so a
        # markdown repo with a renderer profile counts as supported while one
        # without stays a blocker. Behaviour for changie/fragments unchanged:
        # scan() sets auto=True exactly for changie.
        supported = bool(cl.get("auto"))
        note = ("" if supported else f"unsupported changelog system "
                f"({cl.get('system')}) — cannot auto-generate")
        # `auto` only answers "is there a renderer for this repo". The caller
        # may additionally supply `changelog_probe` — a (ok, reason) dry-run of
        # the render against THIS patch and THIS live checkout. Without it the
        # gate can pass a bundle the ship path then fails with
        # `changelog_failed`, e.g. in the post-release window where
        # `## UNRELEASED` does not exist (audit BUG5-int).
        if supported and changelog_probe is not None and not changelog_probe[0]:
            supported = False
            note = changelog_probe[1] or "changelog entry cannot be rendered"
        row("changelog entry", True, supported, auto=supported,
            manual=not supported, confidence=cl.get("confidence", 0.5),
            evidence=cl.get("evidence"), note=note)

    if ai.get("mandatory"):
        can = bool(ai.get("auto")) and human_owned
        row("AI-usage disclosure", True, can, auto=bool(ai.get("auto")),
            manual=not ai.get("auto"), confidence=ai.get("confidence", 0.5),
            evidence=ai.get("evidence"),
            note="" if can else ("no disclosure format detected" if not ai.get("auto")
                                 else "account must be human-owned"))
    if ai.get("human_owned_required"):
        row("human-owned account", True, human_owned,
            confidence=ai.get("confidence", 0.5), evidence=ai.get("evidence"),
            note="" if human_owned else "policy forbids bot-account submissions")

    if cla.get("required"):
        row("CLA signed", True, True, manual=True,
            confidence=cla.get("confidence", 0.5), evidence=cla.get("evidence"),
            note="satisfiable via the CLA bot (human action)")
    if dco.get("required"):
        row("DCO sign-off", True, True, auto=True,
            confidence=dco.get("confidence", 0.5), evidence=dco.get("evidence"))
    if il.get("required"):
        row("issue linkage", False, True, auto=True,
            confidence=il.get("confidence", 0.5), evidence=il.get("evidence"))
    if cc.get("mandatory"):
        # The pipeline already writes conventional-commits ("fix: <summary>")
        # messages, which satisfy commitlint / conventional-commits (the common
        # case). Marked satisfied rather than an unconditional hard blocker.
        row("commit message convention", True, True, auto=True,
            confidence=cc.get("confidence", 0.5), evidence=cc.get("evidence"),
            note=f"pipeline writes conventional '{cc.get('convention')}' commits")

    blockers = [x for x in rows if x["mandatory"] and not x["satisfied"]]
    return {"rows": rows, "blockers": blockers, "ok": not blockers}


def format_report(report):
    lines = []
    for x in report["rows"]:
        mark = "OK " if x["satisfied"] else "!! "
        how = ("auto" if x["auto_satisfied"] else
               "manual" if x["manual_required"] else
               "—" if x["satisfied"] else "BLOCKED")
        lines.append(f"  [{mark}] {x['requirement']:26} {how:7} "
                     f"conf={x['confidence']:.2f} "
                     f"{('src=' + str(x['evidence'])) if x['evidence'] else ''}"
                     f"{('  <- ' + x['note']) if x['note'] else ''}")
    lines.append(f"  gate: {'PASS' if report['ok'] else 'STOP'}"
                 + (f" (blockers: {', '.join(b['requirement'] for b in report['blockers'])})"
                    if report["blockers"] else ""))
    return "\n".join(lines)
